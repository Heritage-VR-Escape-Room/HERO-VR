"""Write ASSET_CREDITS.md and public/credits.json from tools/assets/manifest.json.

  py -3 -I tools/assets/make_credits.py

public/credits.json is read by src/ui/credits.ts: { entries: [{asset, author, license, source}], notes: [] }.
Hand-maintained entries (HDRI, fonts) live in STATIC below; the manifest adds every downloaded or code-built slot
that carries a third-party asset. Entries marked source "code"/"alias" have no third-party content.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
manifest = json.loads((ROOT / "tools" / "assets" / "manifest.json").read_text(encoding="utf-8"))

STATIC = [
    {
        "asset": "Kloppenheim 07 (Pure Sky) HDRI, night sky placeholder",
        "file": "public/assets/hdri_night/kloppenheim_07_puresky_1k.hdr",
        "author": "Greg Zaal (original), Jarod Guest (sky edits)",
        "license": "CC0 1.0",
        "source": "https://polyhaven.com/a/kloppenheim_07_puresky",
    },
    {
        "asset": "IM Fell English (UI headings)",
        "file": "@fontsource/im-fell-english",
        "author": "Igino Marini (Fell Types revival)",
        "license": "SIL Open Font License 1.1",
        "source": "https://fontsource.org/fonts/im-fell-english",
    },
    {
        "asset": "Amiri (Arabic headings, plaque)",
        "file": "@fontsource/amiri",
        "author": "The Amiri Project Authors (Khaled Hosny)",
        "license": "SIL Open Font License 1.1",
        "source": "https://github.com/aliftype/amiri",
    },
    {
        "asset": "Noto Sans (UI body text)",
        "file": "@fontsource/noto-sans",
        "author": "The Noto Project Authors",
        "license": "SIL Open Font License 1.1",
        "source": "https://github.com/notofonts/latin-greek-cyrillic",
    },
    {
        "asset": "Noto Naskh Arabic (Arabic body text)",
        "file": "@fontsource/noto-naskh-arabic",
        "author": "The Noto Project Authors",
        "license": "SIL Open Font License 1.1",
        "source": "https://github.com/notofonts/arabic",
    },
]

NOTES = [
    "Fritz (companion raven): the in-game bird is the CC-BY 'Crow' model credited above, driven by Fritz's own "
    "procedural motion for any clip the model lacks (`fly`, `perch`, `idle`, `caw`); until the model is attached the "
    "bird is a built-in low-poly primitive.",
    "The pyramid and the Schloss are built in code from the CC0 Poly Haven sandstone texture credited above; "
    "no third-party mesh. The plane trees reuse the linden model.",
    "Models were rescaled, re-pivoted, decimated where heavy and compressed (meshopt, WebP); otherwise unmodified.",
    "`public/credits.json` mirrors this file for the in-game Credits screen; both are generated by "
    "`tools/assets/make_credits.py`.",
]

rows = list(STATIC)
for e in manifest["entries"]:
    if e["source"] in ("code", "alias") or e.get("existing"):
        continue
    folder = f"public/assets/{e['slug']}/"
    rows.append({
        "asset": f"{e['title']} ({e['slot']})",
        "file": folder,
        "author": e["author"],
        "license": e["license"],
        "source": e["url"],
    })

(ROOT / "public" / "credits.json").write_text(
    json.dumps(
        {"entries": [{k: r[k] for k in ("asset", "author", "license", "source")} for r in rows], "notes": NOTES},
        indent=2,
        ensure_ascii=False,
    )
    + "\n",
    encoding="utf-8",
)

lines = [
    "# Asset credits",
    "",
    "Every third-party asset in the game. Allowed licenses: CC0, CC-BY, OFL (fonts).",
    "Generated by `tools/assets/make_credits.py` from `tools/assets/manifest.json`; do not edit by hand.",
    "",
    "| Asset | File | Source | Author | License |",
    "|---|---|---|---|---|",
]
for r in rows:
    lic = r["license"].replace("SIL Open Font License", "OFL")
    cells = [r["asset"], f"`{r['file']}`", r["source"], r["author"], lic]
    lines.append("| " + " | ".join(c.replace("|", r"\|") for c in cells) + " |")
lines += ["", "## Notes", ""] + [f"- {n}" for n in NOTES] + [""]
(ROOT / "ASSET_CREDITS.md").write_text("\n".join(lines), encoding="utf-8")
print(f"{len(rows)} credit rows")
